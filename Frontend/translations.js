function t(key) {
  const lang = localStorage.getItem('netclick_ui_lang') || 'en';
  return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS.en[key] || key;
}

function applyTranslations() {
  // Nav buttons
  const navBtns = document.querySelectorAll('.nav-btn');
  if (navBtns[0]) navBtns[0].textContent = t('nav_personalised');
  if (navBtns[1]) navBtns[1].textContent = t('nav_watchlist');
  if (navBtns[2]) navBtns[2].textContent = t('nav_chatbot');

  // Sign out
  const logoutBtn = document.getElementById('logoutBtn');
  if (logoutBtn) logoutBtn.textContent = t('sign_out');

  // Stats labels
  const statLabels = document.querySelectorAll('.stat-label');
  if (statLabels[0]) statLabels[0].textContent = t('stat_watched');
  if (statLabels[1]) statLabels[1].textContent = t('stat_hours');
  if (statLabels[2]) statLabels[2].textContent = t('stat_genre');

  // Tab headers
  const chatbotHeader = document.querySelector('#tab-chatbot .tab-header h2');
  if (chatbotHeader) chatbotHeader.textContent = t('chatbot_title');
  const chatbotSub = document.querySelector('#tab-chatbot .tab-header p');
  if (chatbotSub) chatbotSub.textContent = t('chatbot_sub');

  const watchlistHeader = document.querySelector('#tab-watchlist .header-content h2');
  if (watchlistHeader) watchlistHeader.textContent = t('watchlist_title');
  const watchlistSub = document.querySelector('#tab-watchlist .header-content p');
  if (watchlistSub) watchlistSub.textContent = t('watchlist_sub');

  // Filters
  const filtersTitle = document.querySelector('.filters-header h3');
  if (filtersTitle) filtersTitle.textContent = t('filters_title');
  const resetBtn = document.getElementById('resetFilters');
  if (resetBtn) resetBtn.textContent = t('filters_reset');
  const applyBtn = document.getElementById('applyFilters');
  if (applyBtn) applyBtn.textContent = t('filters_apply');

  const filterLabels = document.querySelectorAll('.filter-group label');
  const labelKeys = ['filter_rating','filter_duration','filter_language','filter_year','filter_popularity','filter_runtime'];
  filterLabels.forEach((l, i) => { if (labelKeys[i]) l.textContent = t(labelKeys[i]); });

  // Chatbot
  const chatPrompt = document.getElementById('chatPrompt');
  if (chatPrompt) chatPrompt.placeholder = t('chatbot_placeholder');
  const chatSubmit = document.getElementById('chatSubmit');
  if (chatSubmit && chatSubmit.textContent !== t('chatbot_thinking'))
    chatSubmit.textContent = t('chatbot_btn');
  const tryAsking = document.querySelector('.chatbot-examples p');
  if (tryAsking) tryAsking.textContent = t('try_asking');

  // Popup buttons
  const watchedBtn   = document.getElementById('watchedBtn');
  if (watchedBtn)   watchedBtn.textContent   = t('mark_watched');
  const watchlistBtn = document.getElementById('watchlistBtn');
  if (watchlistBtn && !watchlistBtn.classList.contains('in-watchlist'))
    watchlistBtn.textContent = '+ ' + t('add_watchlist');

  // Rating popup
  const ratingH3 = document.querySelector('.rating-card h3');
  if (ratingH3) ratingH3.textContent = t('great_choice');
  const ratingP = document.querySelector('.rating-card p');
  if (ratingP) ratingP.textContent = t('feedback_msg');
  const thumbsUp = document.getElementById('thumbsUp');
  if (thumbsUp) thumbsUp.textContent = t('loved_it');
  const thumbsDown = document.getElementById('thumbsDown');
  if (thumbsDown) thumbsDown.textContent = t('not_for_me');

  // Profile panel
  const profileTitle = document.querySelector('.profile-card h2');
  if (profileTitle) profileTitle.textContent = t('profile_title');

  // Where to watch
  const whereWatch = document.querySelector('.streaming-where h4');
  if (whereWatch) whereWatch.textContent = t('where_watch');

  // Greeting sub
  const greetingSub = document.querySelector('#tab-personalised .tab-header p');
  if (greetingSub) greetingSub.textContent = t('greeting_sub');
}

window.t = t;
window.applyTranslations = applyTranslations;